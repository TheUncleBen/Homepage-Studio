# Builds Studio's search index for the built-in logos from a checkout of the
# Dashboard Icons project (https://github.com/homarr-labs/dashboard-icons,
# Apache-2.0). Run it against the pinned commit below:
#   git clone https://github.com/homarr-labs/dashboard-icons.git di
#   git -C di checkout <ICONS_COMMIT>
#   python3 -I scripts/icons/build-icon-index.py di
# It writes:
# - homepage/public/studio-icons/index.json: [name, search words] per logo,
#   loaded only when someone opens the icon chooser;
# - homepage/src/components/studio/icon-variants.mjs: the logos that have a
#   light version for dark themes.
import json
import os
import re
import sys

ICONS_COMMIT = "83f32e08257b66fbd971ac8d7645f5b38d52e85d"
NAME = re.compile(r"^[a-z0-9][a-z0-9.-]{0,99}$")

source = sys.argv[1]
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
with open(os.path.join(source, "metadata.json"), encoding="utf-8") as handle:
    metadata = json.load(handle)

index = []
light = {}
for name in sorted(metadata):
    if not NAME.match(name):
        continue
    entry = metadata[name] or {}
    words = [name.replace("-", " ")]
    for alias in entry.get("aliases") or []:
        if isinstance(alias, str):
            words.append(alias.lower())
    for category in entry.get("categories") or []:
        if isinstance(category, str):
            words.append(category.lower().replace("-", " "))
    index.append([name, " ".join(dict.fromkeys(words))[:300]])
    variant = (entry.get("colors") or {}).get("light")
    if isinstance(variant, str) and NAME.match(variant) and variant != name:
        light[name] = variant

out_dir = os.path.join(root, "homepage", "public", "studio-icons")
os.makedirs(out_dir, exist_ok=True)
with open(os.path.join(out_dir, "index.json"), "w", encoding="utf-8") as handle:
    json.dump({"commit": ICONS_COMMIT, "icons": index}, handle, separators=(",", ":"))
    handle.write("\n")

with open(os.path.join(root, "homepage", "src", "components", "studio", "icon-variants.mjs"), "w", encoding="utf-8") as handle:
    handle.write("// Generated by scripts/icons/build-icon-index.py from Dashboard Icons\n")
    handle.write(f"// ({ICONS_COMMIT}). Logos with a light version for dark themes.\n")
    handle.write("export const LIGHT_VARIANTS = Object.freeze(")
    handle.write(json.dumps(light, separators=(",", ":"), sort_keys=True))
    handle.write(");\n")

print(len(index), "logos,", len(light), "with a light version")
